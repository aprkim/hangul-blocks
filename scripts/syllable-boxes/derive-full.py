"""Layout templates for every vowel, with and without a final consonant, from measure-full.json.

Writes src/fullBoxes.ts: per vowel, the boxes (stroke centerlines, 100 x 100 frame, same scale as
src/syllableBoxes.ts) of the initial consonant, the vowel (compound vowels like ㅘ in two parts:
the flat part under the consonant and the tall part on the right) and the final consonant.

usage: python3 derive-full.py <dir with measure-full.json> <path to src/fullBoxes.ts>
"""
import json, statistics as st, sys
from collections import Counter

S, OUT = sys.argv[1], sys.argv[2]
d = json.load(open(f'{S}/measure-full.json'))
SYL, out = d['SYL'], d['out']
FONTS = list(out)
BODY = 76
SIDE, FLAT, MIXED = 'ㅏㅐㅑㅒㅓㅔㅕㅖㅣ', 'ㅗㅛㅜㅠㅡ', 'ㅘㅙㅚㅝㅞㅟㅢ'
cls = lambda v: 'side' if v in SIDE else 'flat' if v in FLAT else 'mixed'
union = lambda bs: {'x0': min(b['x0'] for b in bs), 'y0': min(b['y0'] for b in bs), 'x1': max(b['x1'] for b in bs), 'y1': max(b['y1'] for b in bs)}
cx = lambda b: (b['x0'] + b['x1']) / 2
cy = lambda b: (b['y0'] + b['y1']) / 2
w = lambda b: b['x1'] - b['x0']
h = lambda b: b['y1'] - b['y0']

def split(s, comps):
    """Initial, vowel parts and final of one measured syllable."""
    rest = list(comps)
    fin = None
    if s['f']:
        fin = max(rest, key=lambda b: b['y0']); rest.remove(fin)
    k = cls(s['v'])
    if k == 'side':
        cons = min(rest, key=cx)
    elif k == 'flat':
        cons = min(rest, key=lambda b: b['y0'])
    else:
        cons = min(rest, key=lambda b: cx(b) + cy(b))
    rest.remove(cons)
    if not rest:
        return None
    if k == 'mixed':
        flat = max(rest, key=lambda b: w(b) / max(h(b), 1))
        tall = [b for b in rest if b is not flat]
        if not tall:
            return None
        return {'cons': cons, 'flat': flat, 'tall': union(tall), 'final': fin}
    return {'cons': cons, 'vowel': union(rest), 'final': fin}

boxes = {}  # (vowel, hasFinal) -> part -> list of normalized boxes
for n in FONTS:
    per = out[n]
    base = [s for s in SYL if s.get('base')]
    # Stroke thickness and overall extent, exactly as derive.py does it.
    def vowel_of(c, side):
        size = (lambda b: h(b)) if side else (lambda b: w(b))
        return max(c, key=size)
    tv = st.median([w(vowel_of(per[c], True)) for c in '기니미비'])
    th = st.median([h(vowel_of(per[c], False)) for c in '그느므브'])
    allc = [b for s in base for b in per[s['ch']]]
    gx0 = min(b['x0'] for b in allc) + tv / 2; gx1 = max(b['x1'] for b in allc) - tv / 2
    gy0 = min(b['y0'] for b in allc) + th / 2; gy1 = max(b['y1'] for b in allc) - th / 2
    k = BODY / max(gx1 - gx0, gy1 - gy0); mx = (gx0 + gx1) / 2; my = (gy0 + gy1) / 2
    def norm(b):
        x0 = b['x0'] + tv / 2; x1 = max(b['x1'] - tv / 2, x0); y0 = b['y0'] + th / 2; y1 = max(b['y1'] - th / 2, y0)
        return [50 + (x0 - mx) * k, 50 + (y0 - my) * k, (x1 - x0) * k, (y1 - y0) * k]
    tests = [s for s in SYL if not s.get('base')]
    # Keep a syllable only when its piece count is this font's usual count for that vowel
    # (fewer means two parts touch; more means a part broke apart).
    usual = {}
    for s in tests:
        usual.setdefault((s['v'], bool(s['f'])), Counter())[len(per[s['ch']])] += 1
    for s in tests:
        key = (s['v'], bool(s['f']))
        if len(per[s['ch']]) < 2 or len(per[s['ch']]) != usual[key].most_common(1)[0][0]:
            continue
        parts = split(s, per[s['ch']])
        if not parts:
            continue
        for name, b in parts.items():
            if b is not None:
                boxes.setdefault(key, {}).setdefault(name, []).append(norm(b))

r = lambda v: round(v * 2) / 2
fmt = lambda b: '[' + ', '.join('%g' % r(x) for x in b) + ']'
lines = []
for v in SIDE + FLAT + MIXED:
    for fin in (False, True):
        parts = boxes.get((v, fin))
        if not parts:
            print('missing', v, fin); continue
        med = {name: [st.median([b[j] for b in bs]) for j in range(4)] for name, bs in parts.items()}
        count = min(len(bs) for bs in parts.values())
        order = ['cons', 'vowel', 'flat', 'tall', 'final']
        body = ', '.join(f'{p}: {fmt(med[p])}' for p in order if p in med)
        lines.append(f"  '{v}{'+' if fin else ''}': {{ {body} }}, // {count} samples")
open(OUT, 'w').write(f"""// Generated by scripts/syllable-boxes/derive-full.py from measure-full.cjs: do not edit.
// Where each part of a syllable goes, per vowel, without and with a final consonant ('+'):
// medians over 7 school and screen fonts and four initials and finals (ㄱ ㄴ ㅁ ㅇ). Boxes are
// stroke centerlines on the 100 x 100 frame, on the same scale as syllableBoxes.ts. Compound
// vowels (ㅘ ...) come in two parts: 'flat' under the consonant and 'tall' on the right.

import type {{ Box }} from './syllableBoxes'

export type FullBoxes = {{ cons: Box; vowel?: Box; flat?: Box; tall?: Box; final?: Box }}

export const FULL_BOXES: Record<string, FullBoxes> = {{
{chr(10).join(lines)}
}}
""")
print('\n'.join(lines))
